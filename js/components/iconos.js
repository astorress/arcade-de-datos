ICONOS['flecha-izq'] = espejo(ICONOS['flecha-der']);

const escapar = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

const cache = new Map();

/** Convierte la cuadrícula en <rect>s, uniendo píxeles contiguos de la misma fila y color. */
function cuerpo(nombre) {
  if (cache.has(nombre)) return cache.get(nombre);
  const grupos = {};
  ICONOS[nombre].forEach((fila, y) => {
    let x = 0;
    while (x < fila.length) {
      const c = fila[x];
      let fin = x + 1;
      while (fin < fila.length && fila[fin] === c) fin++;
      if (PALETA[c]) (grupos[c] ||= []).push(`<rect x="${x}" y="${y}" width="${fin - x}" height="1"/>`);
      x = fin;
    }
  });
  const svg = Object.keys(PALETA)
    .filter((c) => grupos[c])
    .map((c) => `<g ${PALETA[c]}>${grupos[c].join('')}</g>`)
    .join('');
  cache.set(nombre, svg);
  return svg;
}

/** Devuelve el SVG del ícono como string ('' si no existe). */
export function icono(nombre, { tam = 20, clase = '', titulo = '' } = {}) {
  if (!Object.prototype.hasOwnProperty.call(ICONOS, nombre)) return '';
  const a11y = titulo ? `role="img"` : `aria-hidden="true" focusable="false"`;
  const t = titulo ? `<title>${escapar(titulo)}</title>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" width="${tam}" height="${tam}" shape-rendering="crispEdges" class="${escapar(`icono ${clase}`.trim())}" ${a11y}>${t}${cuerpo(nombre)}</svg>`;
}
